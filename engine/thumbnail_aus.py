#!/usr/bin/env python3
"""Thumbnail maker for the Aussie car channel.

Look (channel rule, from video 4 on):
  * background photo with stronger contrast/saturation and a light blur (depth), darkened toward the text side
  * a fictional male persona in the foreground whose expression matches the story (shocked, worried, angry, ...),
    generated by the AI agent on a solid green backdrop and keyed out here, with a soft shadow (no white rim)
  * big two-line headline (white + yellow) with heavy outline, red tag above it, optional yellow badge top corner

Usage:
    python3 thumbnail_aus.py --bg bg.jpg --persona persona_green.jpg --line1 "10 BRANDS IN" --line2 "TROUBLE" \
        --tag "AUSTRALIA 2026" --badge "16 JEEPS SOLD" --badge-sub "in a whole month (Sept 2026)" --out thumb.jpg
Persona prompt to give the AI agent (ai_prompts.json, with "guard": "fictional" and its own "style"):
    "Waist-up portrait of a fictional Australian man in his 40s, <EXPRESSION>, looking at the camera,
     plain solid bright green studio background (#00FF00), even lighting"
"""
import argparse, os
import numpy as np
from PIL import Image, ImageDraw, ImageEnhance, ImageFilter, ImageFont, ImageOps

HERE = os.path.dirname(os.path.abspath(__file__))
W, H = 1280, 720
YEL, RED, WHITE, BLACK = (255, 212, 0), (225, 12, 6), (255, 255, 255), (8, 8, 10)


def font(name, size):
    for p in [os.path.join(HERE, "fonts", name), f"/usr/share/fonts/opentype/inter/{name}"]:
        if os.path.exists(p):
            return ImageFont.truetype(p, size)
    return ImageFont.load_default(size)


def background(path, blur, side):
    im = ImageOps.fit(Image.open(path).convert("RGB"), (W, H), Image.LANCZOS)
    im = ImageEnhance.Color(im).enhance(1.35)
    im = ImageEnhance.Contrast(im).enhance(1.30)
    im = im.filter(ImageFilter.GaussianBlur(blur))
    # darken the text side (left) and the bottom so the headline pops
    x = np.linspace(0, 1, W)[None, :] if side == "left" else np.linspace(1, 0, W)[None, :]
    y = np.linspace(0, 1, H)[:, None]
    shade = np.clip(0.72 * (1 - x) ** 1.4 + 0.55 * y ** 2.2, 0, 0.85)
    a = np.asarray(im).astype(np.float32) * (1 - shade[..., None])
    return Image.fromarray(a.clip(0, 255).astype(np.uint8))


def key_green(path):
    """Green-screen key -> RGBA, with despill so no green fringe remains."""
    im = Image.open(path).convert("RGB")
    a = np.asarray(im).astype(np.float32)
    r, g, b = a[..., 0], a[..., 1], a[..., 2]
    greenness = g - np.maximum(r, b)                       # how much greener than the other channels
    alpha = np.clip(1 - (greenness - 25) / 60, 0, 1)        # 25..85 ramp: soft edge
    a[..., 1] = np.minimum(g, np.maximum(r, b) + 8)         # despill
    rgba = np.dstack([a, alpha * 255]).clip(0, 255).astype(np.uint8)
    out = Image.fromarray(rgba, "RGBA")
    m = out.split()[3].filter(ImageFilter.MinFilter(3)).filter(ImageFilter.GaussianBlur(1.2))
    out.putalpha(m)
    bbox = m.point(lambda v: 255 if v > 40 else 0).getbbox()
    return out.crop(bbox) if bbox else out


def place_persona(canvas, persona, side):
    ph = int(H * 1.02)
    pw = int(persona.width * ph / persona.height)
    p = persona.resize((pw, ph), Image.LANCZOS)
    p = ImageEnhance.Contrast(p).enhance(1.12)
    x = W - pw + int(pw * 0.08) if side == "left" else -int(pw * 0.08)
    y = H - ph + 10
    alpha = p.split()[3]
    # soft dark shadow behind
    shadow = Image.new("RGBA", canvas.size, (0, 0, 0, 0))
    sh = Image.new("RGBA", p.size, (0, 0, 0, 200)); sh.putalpha(alpha.point(lambda v: v * 0.8))
    shadow.paste(sh, (x - 18, y + 6), sh)
    canvas.alpha_composite(shadow.filter(ImageFilter.GaussianBlur(18)))
    canvas.alpha_composite(p, (x, y))   # no white rim (user preference)


def outlined(d, xy, text, f, fill, stroke=7):
    d.text(xy, text, font=f, fill=fill, stroke_width=stroke, stroke_fill=BLACK)


def fit(d, text, name, size, max_w):
    while size > 40:
        f = font(name, size)
        if d.textlength(text, font=f) <= max_w:
            return f
        size -= 4
    return font(name, 40)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bg", required=True); ap.add_argument("--persona"); ap.add_argument("--out", required=True)
    ap.add_argument("--line1", required=True); ap.add_argument("--line2", required=True)
    ap.add_argument("--tag", default=""); ap.add_argument("--badge", default=""); ap.add_argument("--badge-sub", default="")
    ap.add_argument("--blur", type=float, default=3.5); ap.add_argument("--text-side", default="left")
    a = ap.parse_args()
    canvas = background(a.bg, a.blur, a.text_side).convert("RGBA")
    if a.persona:
        place_persona(canvas, key_green(a.persona), a.text_side)
    d = ImageDraw.Draw(canvas)
    max_w = W * (0.62 if a.persona else 0.9)
    x0 = 40 if a.text_side == "left" else W - 40 - max_w
    f1 = fit(d, a.line1, "InterDisplay-Black.otf", 120, max_w)
    f2 = fit(d, a.line2, "InterDisplay-Black.otf", 140, max_w)
    y2 = H - 40 - f2.size
    y1 = y2 - f1.size - 6
    if a.tag:
        ft = font("InterDisplay-Black.otf", 46)
        tw = d.textlength(a.tag, font=ft)
        ty = y1 - 78
        d.rectangle([x0, ty, x0 + tw + 34, ty + 66], fill=RED)
        d.text((x0 + 17, ty + 4), a.tag, font=ft, fill=WHITE)
    outlined(d, (x0, y1), a.line1, f1, WHITE)
    outlined(d, (x0, y2), a.line2, f2, YEL, 8)
    if a.badge:
        fb = fit(d, a.badge, "InterDisplay-Black.otf", 72, W * 0.42)
        bw = d.textlength(a.badge, font=fb)
        bx = 36 if a.text_side == "left" else W - bw - 90
        d.rounded_rectangle([bx, 34, bx + bw + 50, 34 + fb.size + 34], radius=16, fill=YEL)
        d.text((bx + 25, 44), a.badge, font=fb, fill=BLACK)
        if a.badge_sub:
            fs = font("Inter-Bold.otf", 26)
            outlined(d, (bx + 4, 34 + fb.size + 44), a.badge_sub, fs, WHITE, 4)
    canvas.convert("RGB").save(a.out, quality=93)
    print("thumbnail ->", a.out)


if __name__ == "__main__":
    main()
